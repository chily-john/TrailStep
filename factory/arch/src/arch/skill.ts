/**
 * The generated agent skill (Story 110, rev 4 decision 5).
 *
 * One text, derived from the manifest: the command contracts, the state
 * contract, and every strict rule's ID + one-line fix recipe. Nothing about a
 * rule is written here — the rule list, the fix text, the severity split, and
 * the budgets all come from `manifest`. Adding, removing, or re-severitising a
 * rule therefore changes this file's output, which is what the drift guard
 * (`skill.test.ts`) pins against the committed artifact.
 *
 * What this file MAY write by hand: command surfaces and their contracts (they
 * are not rule text), the recovery loop, and the pointer to the normative doc.
 * What it may NOT write by hand: rule IDs, rule prose, severities, budgets.
 */

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import type { ArchManifest, RuleId, RuleSpec } from "./manifest.js";

/**
 * The one sanctioned copy of the artifact, repo-relative and `/`-separated.
 *
 * Choice (recorded in the Story 110 completion record): `.agents/skills/<name>/
 * SKILL.md` is the Agent Skills project location this repo's harness discovers
 * from the working directory up to the repository root. On this tree `.agents/`
 * did not exist at all — neither a directory nor a symlink into user config —
 * so creating it is a real, repo-visible directory, never a write through a
 * symlink. It is also not gitignored, so the artifact is committable and the
 * drift guard can read it from a clean checkout.
 */
export const SKILL_ARTIFACT_PATH = ".agents/skills/trailstep-architecture/SKILL.md";

/** The absolute artifact path inside `repoRoot`. */
export function skillArtifactPath(repoRoot: string): string {
  return path.join(repoRoot, ...SKILL_ARTIFACT_PATH.split("/"));
}

/** The committed artifact's text (the drift guard's comparison side). */
export function readCommittedSkill(repoRoot: string): string {
  return readFileSync(skillArtifactPath(repoRoot), "utf8");
}

function rulesWithSeverity(manifest: ArchManifest, severity: RuleSpec["severity"]): RuleId[] {
  return manifest.ruleOrder.filter((rule) => manifest.rules[rule].severity === severity);
}

function ruleList(manifest: ArchManifest): string[] {
  return rulesWithSeverity(manifest, "strict").map(
    (rule) => `- \`${rule}\` — ${manifest.rules[rule].fix}`,
  );
}

function inlineRuleList(manifest: ArchManifest, severity: RuleSpec["severity"]): string {
  const rules = rulesWithSeverity(manifest, severity);
  return rules.length === 0 ? "none" : rules.map((rule) => `\`${rule}\``).join(", ");
}

/**
 * Renders the artifact. The returned text is the exact file content, trailing
 * newline included, so the drift guard is a byte comparison with no trimming.
 */
export function renderSkill(manifest: ArchManifest): string {
  const width = manifest.budgets.folderWidth;
  const lines = manifest.budgets.fileLines;
  return [
    "---",
    "name: trailstep-architecture",
    "description: Recover from TrailStep architecture gate violations. Use when `pnpm arch:check` or `pnpm arch:check --changed` reports a violation, when a diagnostic names a G, S, V, N, M, or T rule, or before declaring architecture-affecting work done.",
    "---",
    "",
    "# TrailStep architecture gate",
    "",
    "<!-- GENERATED by factory/arch/src/arch/skill.ts from factory/arch/src/arch/manifest.ts.",
    "     Do not edit this file: change the manifest, then regenerate with",
    "     `pnpm arch:check --emit-skill <path>`. The drift test fails otherwise. -->",
    "",
    "## Commands",
    "",
    "- `pnpm arch:check --changed` — the gate. Checks only the files this change touches against",
    "  the strict set; exits 1 with one diagnostic per violation, each carrying its fix recipe.",
    "- `pnpm arch:check` — the full-tree scorecard. Always exits 0: a red scorecard is the",
    "  migration backlog, never a pass/fail answer.",
    "- `pnpm arch:explain <rule>` — one rule: severity, doc anchor, fix recipe, and a",
    "  fixture-derived good/bad example.",
    "- `pnpm verify:quick` — the fast loop: full-tree lint plus `arch:check --changed`.",
    "  It is not a typecheck substitute.",
    "- `pnpm verify` — the full gate: lint, typecheck, `arch:check --report`, `test:fast`.",
    "",
    "Run `pnpm verify` before declaring done.",
    "",
    "## State contract",
    "",
    "- `--changed` blocks; the full tree reports; the verify lanes compose both scopes.",
    "- Report-only rules never block; review-set rules have no checker at all.",
    "- Severity lives in the manifest, never in a flag: there is no `--skip <rule>`.",
    "- A diagnostic's `Fix:` line is the remediation; the rule anchor explains why.",
    "",
    "## Strict rules (these block)",
    "",
    ...ruleList(manifest),
    "",
    `Report-only (visible, never blocking): ${inlineRuleList(manifest, "report")}.`,
    `Review set (no checker): ${inlineRuleList(manifest, "review")}.`,
    `Budgets: folder width gate ${width.gate} / target ${width.target} direct children;`,
    `file lines ${lines.limit} (${lines.biomeRule}, ${lines.owner}-owned).`,
    "",
    "## Recovering from one diagnostic",
    "",
    "1. Apply the diagnostic's `Fix:` to the file it names — that recipe is the whole change.",
    "2. `pnpm arch:explain <rule>` when you need the anchor and a good/bad example.",
    "3. Iterate with `pnpm verify:quick`; run `pnpm verify` before declaring done.",
    `4. Normative source, single home: ${manifest.docUri} — read it; never restate it.`,
    "",
  ].join("\n");
}

/** Renders and writes the artifact, creating its directory. Returns the byte length. */
export function writeSkill(manifest: ArchManifest, filePath: string): number {
  const text = renderSkill(manifest);
  mkdirSync(path.dirname(filePath), { recursive: true });
  writeFileSync(filePath, text, "utf8");
  return Buffer.byteLength(text, "utf8");
}
